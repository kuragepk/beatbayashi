// Derived icons: exact mirrors / rotations of a drawn one, so the pair always matches pixel for pixel.
const mirrorX = (rows) => rows.map((r) => [...r].reverse().join(''));
const transpose = (rows) => rows[0].split('').map((_, x) => rows.map((r) => r[x]).join(''));
ICONS['arrow-right'] = { meaning: 'move later', from: 'arrow-left (mirrored)', rows: mirrorX(ICONS['arrow-left'].rows) };
ICONS['arrow-up'] = { meaning: 'move up', from: 'arrow-left (transposed)', rows: transpose(ICONS['arrow-left'].rows) };
ICONS['arrow-down'] = { meaning: 'move down', from: 'arrow-up (flipped)', rows: [...ICONS['arrow-up'].rows].reverse() };
ICONS.redo = { meaning: 'retry', from: 'undo (mirrored)', rows: mirrorX(ICONS.undo.rows) };
